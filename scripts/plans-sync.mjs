// Rewrites electron/shared/feature-plans.ts from @hivetty/plans (HIVE-268). Reads the sibling checkout's built
// package, so the app's build never touches hivetty-cloud or the network. HIVETTY_CLOUD_DIR overrides the folder.
import { existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const cloud = resolve(process.env.HIVETTY_CLOUD_DIR ?? resolve(root, '../hivetty-cloud'));
const entry = resolve(cloud, 'packages/plans/dist/index.js');
if (!existsSync(entry)) {
  console.error(`No built @hivetty/plans at ${entry}. Run \`pnpm --filter @hivetty/plans build\` in ${cloud}.`);
  process.exit(1);
}
const { PLANS, TRIAL_PLAN } = await import(pathToFileURL(entry).href);

const order = Object.keys(PLANS);
const cheapest = {};
for (const key of order) for (const feature of PLANS[key].features) cheapest[feature] ??= key;

const q = (s) => `'${s}'`;
const prop = (s) => (/^[a-z]+$/i.test(s) ? s : q(s));
const body = `/**
 * GENERATED by \`pnpm plans:sync\` from hivetty-cloud's @hivetty/plans (HIVE-268). Do not edit by hand.
 * Prices are left out on purpose: the package's are placeholders the app never renders.
 */
export const PLAN_ORDER = [${order.map(q).join(', ')}] as const;
export type PlanKey = (typeof PLAN_ORDER)[number];

export const PLAN_NAMES: Readonly<Record<PlanKey, string>> = {
${order.map((key) => `  ${prop(key)}: ${q(PLANS[key].name)},`).join('\n')}
};

/** The cheapest plan whose features include each key. */
export const FEATURE_PLANS: Readonly<Record<string, PlanKey>> = {
${Object.entries(cheapest).map(([feature, key]) => `  ${prop(feature)}: ${q(key)},`).join('\n')}
};

export const TRIAL_PLAN: PlanKey = ${q(TRIAL_PLAN)};
`;
writeFileSync(resolve(root, 'electron/shared/feature-plans.ts'), body);
console.log(`feature-plans.ts: ${order.length} plans, ${Object.keys(cheapest).length} features`);
